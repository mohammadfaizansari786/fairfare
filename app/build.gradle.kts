android {
  namespace = "com.example"
  compileSdk { version = release(37) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.aistudio.fairfare.trqzn"
    minSdk = 26
    targetSdk = 37
    versionCode = 1
    versionName = "1.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

    // BuildConfig fields for secrets come from the Secrets Gradle plugin, which
    // reads `.env` (falling back to `.env.example`) — see the `secrets { }` block
    // below. The plugin does not populate manifest placeholders, so those are
    // wired here from the same environment variables. Nothing is hardcoded.
    //
    // A missing key is not a build failure: the map renderer detects the `MY_…`
    // placeholder and falls back to keyless tile CDNs.
    manifestPlaceholders["MAPS_API_KEY"] =
      System.getenv("MAPS_API_KEY") ?: "MY_MAPS_API_KEY"
    manifestPlaceholders["TOMTOM_API_KEY"] =
      System.getenv("TOMTOM_API_KEY") ?: "MY_TOMTOM_API_KEY"
  }

  signingConfigs {
    create("release") {
      // Only wire up the release keystore when it is actually present. Referencing
      // a missing file made every `assembleRelease` fail at configuration time on
      // machines without the signing material.
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      val keystoreFile = file(keystorePath)
      if (keystoreFile.exists()) {
        storeFile = keystoreFile
        storePassword = System.getenv("STORE_PASSWORD")
        keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
        keyPassword = System.getenv("KEY_PASSWORD")
      }
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      // Shrink and obfuscate for release. Room, Moshi, Retrofit and OkHttp all
      // ship consumer R8 rules; app-specific keeps live in proguard-rules.pro.
      isMinifyEnabled = true
      isShrinkResources = true
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")

      val releaseSigning = signingConfigs.getByName("release")
      signingConfig = if (releaseSigning.storeFile?.exists() == true) {
        releaseSigning
      } else {
        // Fall back to debug signing so a release build is still producible
        // locally; CI supplies the real keystore via KEYSTORE_PATH.
        signingConfigs.getByName("debugConfig")
      }
    }
    debug {
      signingConfig = signingConfigs.getByName("debugConfig")
      isMinifyEnabled = false
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}

