    /**
     * Tariffs for a city, falling back to the first seeded city when the
     * requested one has no data.
     *
     * Callers previously filtered [DEFAULT_TARIFFS] inline with a hardcoded
     * `city == "Lucknow"` fallback, which silently showed Lucknow rates for any
     * city that was missing data. Centralising it keeps that fallback explicit
     * and consistent.
     */
    fun tariffsForCityOrFallback(cityName: String): List<TariffEntity> {
        val exact = DEFAULT_TARIFFS.filter { it.city.equals(cityName, ignoreCase = true) }
        if (exact.isNotEmpty()) return exact

        val fallbackCity = CITIES.first().name
        return DEFAULT_TARIFFS.filter { it.city.equals(fallbackCity, ignoreCase = true) }
    }
